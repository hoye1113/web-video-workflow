def main():
    d = json.loads(SRC.read_text(encoding="utf-8"))
    hit, miss = 0, []
    for p in d["pages"]:
        for i, c in enumerate(p["cues"]):
            if c in FIX:
                p["cues"][i] = FIX[c]
                hit += 1
    used = set()
    for p in d["pages"]:
        used |= set(p["cues"])
    for k in FIX:
        if k not in used and FIX[k] not in used:
            miss.append(k)
    SRC.write_text(json.dumps(d, ensure_ascii=False, indent=1), encoding="utf-8")
    print(f"改了 {hit} 条（表里 {len(FIX)} 条）"
          + (f"，没对上 {len(miss)} 条：{miss[:3]}" if miss else ""))
    print("接下来：make_script_js.py --from-source → check_cues.py → make_voice.py（重配音）")


if __name__ == "__main__":
    main()
