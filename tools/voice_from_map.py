"""Cut a user's audio into the cues of a noir project and write voice.js.

Usage:
    python tools/voice_from_map.py noir-1112 "E:\\音频素材\\1112.mp4"

The project must contain cue-audio-map.json (page -> cue -> start) and
script-source.json (the exact cue text). Each cue is cut from its start to the
next cue's start (last cue to the end of the audio), so the final film's sound
is the original recording with no inserted silence.
"""
import json
import pathlib
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent


def run(cmd, timeout=300):
    return subprocess.run(cmd, capture_output=True, text=True, encoding="utf-8",
                          errors="replace", timeout=timeout)


def dur_of(f):
    r = run(["ffprobe", "-v", "error", "-show_entries", "format=duration",
             "-of", "default=nw=1:nk=1", str(f)])
    try:
        return round(float((r.stdout or "0").strip() or 0), 3)
    except Exception:  # noqa: BLE001
        return 0.0


def main(argv):
    if len(argv) < 3:
        sys.exit(__doc__)
    proj, audio = argv[1], pathlib.Path(argv[2])
    d = ROOT / "projects" / proj
    cmap = json.loads((d / "cue-audio-map.json").read_text(encoding="utf-8"))
    src = json.loads((d / "script-source.json").read_text(encoding="utf-8"))
    total = dur_of(audio)
    adir = d / "audio"
    adir.mkdir(exist_ok=True)
    for f in adir.glob("*.wav"):
        f.unlink()

    # flatten cues in script order; cue-audio-map is generated from the same order
    flat = []
    for pg in cmap:
        for c in pg["cues"]:
            flat.append((pg["page"], c))
    src_pages = src["pages"]
    assert len(flat) == sum(len(p["cues"]) for p in src_pages), "cue map / script mismatch"

    # cut each cue to the next cue's start (last to the end of the audio)
    voice_pages = []
    k = 0
    for pi, pg in enumerate(src_pages):
        vlist = []
        for ci, text in enumerate(pg["cues"]):
            pid, c = flat[k]
            start = float(c["start"])
            end = float(flat[k + 1][1]["start"]) if k + 1 < len(flat) else total
            if end <= start:
                end = min(total, start + 1.0)
            wav = adir / f"{pg['id']}-{ci}.wav"
            run(["ffmpeg", "-y", "-loglevel", "error",
                 "-ss", f"{max(0.0, start):.3f}", "-to", f"{end:.3f}",
                 "-i", str(audio), "-ar", "48000", "-ac", "2", str(wav)])
            dd = dur_of(wav) or (end - start)
            chars = list(text)
            ks = [round(min(dd * 0.96, (i + 0.5) / max(1, len(chars)) * dd * 0.96), 3)
                  for i in range(len(chars))]
            vlist.append({"t": text, "f": f"audio/{wav.name}", "d": round(dd, 3),
                          "o": 0, "k": ks, "r": 0})
            k += 1
        voice_pages.append(vlist)

    (d / "voice.js").write_text(
        "/* generated by tools/voice_from_map.py from the user's original audio */\n"
        "SCRIPT.VOICE = " + json.dumps({"speaker": "audio", "provider": "audio",
                                        "pages": voice_pages}, ensure_ascii=False) + ";\n",
        encoding="utf-8")
    total2 = sum(c["d"] for pg in voice_pages for c in pg)
    print(f"{len(voice_pages)} pages / {k} cues / audio {total2:.1f}s (source {total:.1f}s)")


if __name__ == "__main__":
    main(sys.argv)
