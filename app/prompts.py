def framing_text(got, framing):
    """写场景提示词里那一段"量出来的构图"。量不出来就说清楚，让模型按默认走。"""
    if not got or not framing:
        return ("没量出来（或这一页还没图）。那就按默认来：`z` 从 1.00 推到 1.07，"
                "`fx`/`fy` 都用 0.5 居中。")
    x, y, w, h = got["box"]
    z0, fx, fy = framing
    return (f"- 主体是：**{got['subject'] or '（没认出来）'}**\n"
            f"- 它的外接框：宽 {w:.0%}、高 {h:.0%}，中心在画面的 ({x + w / 2:.2f}, {y + h / 2:.2f})\n"
            f"- 已经替你算好铺图参数：**`z` 从 {z0:.2f} 走到 {z0 * 1.07:.2f}，`fx` = {fx:.2f}，`fy` = {fy:.2f}**\n"
            f"  这三个数直接用，不要自己另算一套。")


def _split_lines(text, n=3):
    """把屏上字按标点拆成最多 n 条（参考例子的 LINES 用它）。拆不动就原样一条。"""
    import re
    t = (text or "").strip()
    if not t:
        return []
    parts = [x for x in re.split(r"[。！？；\n]+|(?<=[，、])", t) if x.strip()]
    if len(parts) <= n:
        return [p.strip() for p in parts]
    per = max(1, (len(t) + n - 1) // n)                  # 太碎：按字数均分
    return [t[i:i + per].strip() for i in range(0, len(t), per)][:n]


def example_image(shot, assets, palette, pos=1, total=1, framing=None):
    """给贴图页拼一个「写法正确」的参考例子。

    例子里用**这一页真实的图片路径、真实的屏上字、真实的时长、量出来的构图参数** ——
    实测：路径占了位的例子，模型照抄得最准；给通用例子它会自己编一个路径出来。
    """
    import json as _json
    P = assets[0] if assets else "demos/项目名/assets/主图.png"
    # 色板顺序是 [底, 面色, 墨, 次, 强调, 次强调]（见 presets.py 的 palette_list）
    bg = (palette or ["#EFE7DA"])[0]
    ink = palette[2] if len(palette) > 2 else "#1B1A17"
    lines = _split_lines(shot.get("text") or "", 3) or ["（这一页没有屏上字，整段删掉）"]
    z0, fx, fy = (framing or (1.0, 0.5, 0.5))[:3]
    ex = _EX_HEAD.format(
        shot=shot.get("id") or "", dur=float(shot.get("dur") or 12),
        asset=P, bg=bg, ink=ink, lines=_json.dumps(lines, ensure_ascii=False),
        close_const=("\n  const Q = '%s';" % assets[1]) if len(assets) > 1 else "",
        z0=f"{z0:.3f}", z1=f"{z0 * 1.07:.3f}",
    )
    ex += (_EX_CLOSE_ON if len(assets) > 1 else _EX_CLOSE_OFF).format(fx=fx, fy=fy)
    ex += _EX_REVEAL_ON if pos <= 2 else _EX_REVEAL_OFF      # 揭示只给开篇用
    return ex + _EX_TAIL.format(ink=ink)


